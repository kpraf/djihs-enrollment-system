import { Head } from '@inertiajs/react';
import { useEffect } from 'react';

interface Props {
    title: string;
    /** The browser tab and saved-PDF name, e.g. "DJIHS Class List - Grade 11 HUMSS Integrity - SY 2026-2027". */
    documentTitle?: string;
    subtitle: string;
    learners: { lrn: string | null; name: string; sex: string; contact_number: string | null }[];
}

/**
 * A plain class list that opens the print dialog, so it can be printed or
 * saved as PDF (the legacy "Export PDF").
 */
export default function ClassList({ title, documentTitle, subtitle, learners }: Props) {
    useEffect(() => {
        const t = setTimeout(() => window.print(), 400);
        return () => clearTimeout(t);
    }, []);

    const male = learners.filter((l) => l.sex === 'Male').length;

    return (
        <div className="mx-auto max-w-4xl bg-white p-8 text-slate-900 print:p-0">
            <Head title={documentTitle ?? title} />
            <div className="border-primary mb-6 flex items-center gap-4 border-b-2 pb-4">
                <img src="/images/djihs-logo-large.png" alt="" className="size-16" />
                <div>
                    <p className="text-primary text-sm font-semibold tracking-wide uppercase">Don Jose Integrated High School</p>
                    <h1 className="text-2xl font-bold">{title}</h1>
                    <p className="text-sm text-slate-600">{subtitle}</p>
                </div>
            </div>
            <table className="w-full border-collapse text-sm">
                <thead>
                    <tr className="border-b-2 border-slate-300 text-left">
                        <th className="py-2 pr-2">#</th>
                        <th className="py-2 pr-2">LRN</th>
                        <th className="py-2 pr-2">Name</th>
                        <th className="py-2 pr-2">Sex</th>
                        <th className="py-2">Contact Number</th>
                    </tr>
                </thead>
                <tbody>
                    {learners.map((l, i) => (
                        <tr key={i} className="border-b border-slate-200">
                            <td className="py-1.5 pr-2 tabular-nums">{i + 1}</td>
                            <td className="py-1.5 pr-2 font-mono">{l.lrn}</td>
                            <td className="py-1.5 pr-2">{l.name}</td>
                            <td className="py-1.5 pr-2">{l.sex}</td>
                            <td className="py-1.5">{l.contact_number}</td>
                        </tr>
                    ))}
                </tbody>
            </table>
            <p className="mt-6 text-sm">
                Male: {male} · Female: {learners.length - male} · Total: {learners.length}
            </p>
            <p className="mt-8 text-xs text-slate-500 italic">Generated by the DJIHS Enrollment System on {new Date().toLocaleString('en-PH')}.</p>
            <button type="button" className="btn-primary mt-6 print:hidden" onClick={() => window.print()}>
                Print again
            </button>
        </div>
    );
}
